"""The parts of the POC's schedule.py and simulate.py the experiment needs: the day's hours, list-order packing,
duration draws from the German 2019 distributions, and the procedure catalog read from data/catalog.json
(generated by tools/theatre/export_catalog.py, so no pandas or raw CSVs are needed at runtime)."""

from __future__ import annotations

import json
from pathlib import Path
from random import Random

DAY_OPEN = 8 * 60
DAY_CLOSE = 16 * 60

CATALOG_PATH = Path(__file__).resolve().parents[1] / "data" / "catalog.json"

INTERVALS = (
    "AN induction",
    "Surgical Lead-in",
    "Incision-to-closure",
    "Surgical Lead-out",
    "AN emergence",
)

ROOMS = (
    {"id": "OR 1", "specialty": "General"},
    {"id": "OR 2", "specialty": "Trauma"},
    {"id": "OR 3", "specialty": "Gyn & Obstetrics"},
    {"id": "OR 4", "specialty": "Otolaryngology"},
)


def pack_room(cases: list[dict], durations: dict[str, int], cleaning: dict[str, int], open_min: int) -> list[dict]:
    """Place cases in the given order. `cases` must already belong to one room."""
    blocks = []
    cursor = open_min
    for index, case in enumerate(cases):
        start = cursor
        end = start + durations[case["id"]]
        blocks.append(
            {
                "type": "case",
                "case_id": case["id"],
                "room_id": case["room_id"],
                "start_min": start,
                "end_min": end,
                "moved": False,
            }
        )
        if index < len(cases) - 1:
            gap = cleaning[case["specialty"]]
            blocks.append(
                {
                    "type": "turnover",
                    "case_id": case["id"],
                    "room_id": case["room_id"],
                    "start_min": end,
                    "end_min": end + gap,
                    "moved": False,
                }
            )
            cursor = end + gap
        else:
            cursor = end
    return blocks


def plan_day(cases: list[dict], durations: dict[str, int], cleaning: dict[str, int]) -> list[dict]:
    blocks = []
    rooms = []
    for case in cases:
        if case["room_id"] not in rooms:
            rooms.append(case["room_id"])
    for room_id in rooms:
        room_cases = [case for case in cases if case["room_id"] == room_id]
        blocks.extend(pack_room(room_cases, durations, cleaning, DAY_OPEN))
    return blocks


def draw_minutes(step: dict, rng: Random) -> float:
    kind = step["dist"]
    shape_or_mu = step["p1"]
    scale_or_sigma = step["p2"]
    if kind == "lognormal":
        return rng.lognormvariate(shape_or_mu, scale_or_sigma)
    if kind == "gamma":
        return rng.gammavariate(shape_or_mu, scale_or_sigma)
    if kind == "weibull":
        return rng.weibullvariate(scale_or_sigma, shape_or_mu)
    raise ValueError(kind)


def sample_room_minutes(steps: list[dict], rng: Random) -> int:
    total = sum(draw_minutes(step, rng) for step in steps)
    return max(1, int(round(total)))


def load_catalog(path: Path = CATALOG_PATH) -> tuple[dict[str, list[dict]], dict[str, int]]:
    """(pools, cleaning) exactly as the POC's simulate.load_catalog() builds them from the CSVs."""
    payload = json.loads(path.read_text(encoding="utf-8"))
    return payload["pools"], payload["cleaning"]
